/** Tom sugerido para o nome da cor digitado ("Azul royal" → #2647A8); `null` se não reconhece. */
export function colorHexFor(name: string): string | null {
  const n = normalize(name)
  if (!n) return null
  return COLORS.find(([k]) => n.includes(k))?.[1] ?? null
}
